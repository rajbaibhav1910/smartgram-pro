def merge(path, patch):
    with io.open(path, encoding='utf-8') as f:
        data = json.load(f)
    data.setdefault('schemes', {}).update(patch)
    with io.open(path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')

